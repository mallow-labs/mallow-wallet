import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:cryptography/cryptography.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:ledger_solana/ledger_solana.dart' show SolanaDerivationScheme;
import 'package:mallow_wallet/core/crypto/derivation.dart';
import 'package:mallow_wallet/core/social_vault/social_vault_crypto.dart';

/// The vault format must be byte-identical in this app and the web client: a
/// vault created on one has to open on the other. These tests therefore read
/// the shared vector file rather than restating expectations, and that file is
/// produced by an independent Python reference
/// (`tool/social_vault/gen_vectors.py`), not by either implementation — a
/// vector generated by the code under test would only prove self-consistency.
void main() {
  final vectors =
      jsonDecode(
            File('test/assets/social_vault_vectors.json').readAsStringSync(),
          )
          as Map<String, dynamic>;

  Uint8List hex(String s) => Uint8List.fromList([
    for (var i = 0; i < s.length; i += 2)
      int.parse(s.substring(i, i + 2), radix: 16),
  ]);

  String toHex(List<int> b) =>
      b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();

  final payloads = (vectors['payload'] as List).cast<Map<String, dynamic>>();
  final slots = (vectors['slots'] as List).cast<Map<String, dynamic>>();

  group('payload vectors', () {
    for (final v in payloads) {
      test('${v['name']}: seals to the reference ciphertext', () async {
        final payload = SocialVaultPayload.fromJsonString(
          v['payloadJson'] as String,
        );
        expect(payload.toJsonString(), v['payloadJson']);
        expect(SocialVaultCrypto.payloadAad(v['vaultId'] as String), v['aad']);

        final sealed = await SocialVaultCrypto.sealPayload(
          vaultId: v['vaultId'] as String,
          dataKey: hex(v['dataKeyHex'] as String),
          payload: payload,
          nonce: SocialVaultCrypto.decodeBase64UrlNoPad(v['nonce'] as String),
        );
        expect(sealed.nonceWire, v['nonce']);
        expect(sealed.ciphertextWire, v['ciphertext']);
      });

      test('${v['name']}: opens the reference ciphertext', () async {
        final opened = await SocialVaultCrypto.openPayload(
          vaultId: v['vaultId'] as String,
          dataKey: hex(v['dataKeyHex'] as String),
          sealed: SocialVaultSealed.fromWire(
            nonce: v['nonce'] as String,
            ciphertext: v['ciphertext'] as String,
          ),
        );
        expect(opened.toJsonString(), v['payloadJson']);
      });
    }
  });

  // A payload another client sealed without normalising the phrase first:
  // padded, with a double space, a tab and a line break between words, and
  // capitals. It authenticates like any other, and must then read as the
  // same phrase — and so the same wallet — on every client.
  group('a payload whose phrase is not in its one spelling', () {
    final nonCanonical = (vectors['nonCanonicalPayload'] as List)
        .cast<Map<String, dynamic>>();

    test('the vectors are there', () => expect(nonCanonical, isNotEmpty));

    for (final v in nonCanonical) {
      test('${v['name']}: opens to the normalised phrase', () async {
        final opened = await SocialVaultCrypto.openPayload(
          vaultId: v['vaultId'] as String,
          dataKey: hex(v['dataKeyHex'] as String),
          sealed: SocialVaultSealed.fromWire(
            nonce: v['nonce'] as String,
            ciphertext: v['ciphertext'] as String,
          ),
        );
        expect(opened.mnemonic, v['normalizedMnemonic']);
        expect(
          SocialVaultPayload.fromJsonString(
            v['payloadJson'] as String,
          ).mnemonic,
          v['normalizedMnemonic'],
        );
      });

      test('${v['name']}: is sealed again in the one spelling', () async {
        final raw =
            (jsonDecode(v['payloadJson'] as String)
                    as Map<String, dynamic>)['mnemonic']
                as String;
        expect(raw, isNot(v['normalizedMnemonic']));
        expect(
          SocialVaultCrypto.normalizeMnemonic(raw),
          v['normalizedMnemonic'],
        );
        // Writing normalises with the same function reading does.
        expect(
          SocialVaultCrypto.canonicalPayloadJson(SocialVaultPayload(raw)),
          SocialVaultPayload(v['normalizedMnemonic'] as String).toJsonString(),
        );
      });
    }
  });

  group('slot vectors', () {
    for (final v in slots) {
      final kind = SocialVaultSlotKind.fromWireName(v['kind'] as String);

      test('${v['kind']}: KEK, AAD and wrapped key match', () async {
        expect(SocialVaultCrypto.kekInfo(kind), v['kekInfo']);
        expect(
          SocialVaultCrypto.slotAad(
            v['vaultId'] as String,
            v['slotId'] as String,
          ),
          v['aad'],
        );
        final kek = await SocialVaultCrypto.deriveKek(
          slotSecret: hex(v['slotSecretHex'] as String),
          vaultId: v['vaultId'] as String,
          kind: kind,
        );
        expect(toHex(kek), v['kekHex']);

        final wrapped = await SocialVaultCrypto.wrapDataKey(
          vaultId: v['vaultId'] as String,
          slotId: v['slotId'] as String,
          kind: kind,
          slotSecret: hex(v['slotSecretHex'] as String),
          dataKey: hex(v['dataKeyHex'] as String),
          nonce: SocialVaultCrypto.decodeBase64UrlNoPad(v['nonce'] as String),
        );
        expect(wrapped.ciphertextWire, v['wrappedKey']);
      });

      test('${v['kind']}: unwraps the reference key', () async {
        final dataKey = await SocialVaultCrypto.unwrapDataKey(
          vaultId: v['vaultId'] as String,
          slotId: v['slotId'] as String,
          kind: kind,
          slotSecret: hex(v['slotSecretHex'] as String),
          wrapped: SocialVaultSealed.fromWire(
            nonce: v['nonce'] as String,
            ciphertext: v['wrappedKey'] as String,
          ),
        );
        expect(toHex(dataKey), v['dataKeyHex']);
      });
    }
  });

  group('vault key vector', () {
    final v = vectors['vaultKey'] as Map<String, dynamic>;
    final request = v['request'] as Map<String, dynamic>;

    test('derives the reference public key', () async {
      final keyPair = await SocialVaultCrypto.vaultKeyPair(
        dataKey: hex(v['dataKeyHex'] as String),
        vaultId: v['vaultId'] as String,
      );
      expect(toHex(await keyPair.extractPrivateKeyBytes()), v['seedHex']);
      expect(await SocialVaultCrypto.vaultPublicKey(keyPair), v['publicKey']);
    });

    test('builds the reference message and signature', () async {
      final keyPair = await SocialVaultCrypto.vaultKeyPair(
        dataKey: hex(v['dataKeyHex'] as String),
        vaultId: v['vaultId'] as String,
      );
      final body = utf8.encode(request['body'] as String);
      expect(
        SocialVaultCrypto.requestMessage(
          method: request['method'] as String,
          path: request['path'] as String,
          vaultId: v['vaultId'] as String,
          revision: request['revision'] as int,
          body: body,
          timestamp: request['timestamp'] as int,
        ),
        v['message'],
      );
      expect(
        await SocialVaultCrypto.signRequest(
          keyPair: keyPair,
          method: request['method'] as String,
          path: request['path'] as String,
          vaultId: v['vaultId'] as String,
          revision: request['revision'] as int,
          body: body,
          timestamp: request['timestamp'] as int,
        ),
        v['signature'],
      );
    });
  });

  group('negative vectors', () {
    Map<String, dynamic> payloadNamed(String name) =>
        payloads.firstWhere((p) => p['name'] == name);
    Map<String, dynamic> slotOfKind(String kind) =>
        slots.firstWhere((s) => s['kind'] == kind);

    for (final n
        in (vectors['negative'] as List).cast<Map<String, dynamic>>()) {
      test('refuses: ${n['case']}', () async {
        final Future<Object> attempt;
        if (n['target'] == 'payload') {
          final p = payloadNamed(n['from'] as String);
          attempt = SocialVaultCrypto.openPayload(
            vaultId: n['vaultId'] as String,
            dataKey: hex(p['dataKeyHex'] as String),
            sealed: SocialVaultSealed.fromWire(
              nonce: p['nonce'] as String,
              ciphertext: p['ciphertext'] as String,
            ),
          );
        } else {
          final s = slotOfKind(n['from'] as String);
          attempt = SocialVaultCrypto.unwrapDataKey(
            vaultId: s['vaultId'] as String,
            slotId: (n['slotId'] ?? s['slotId']) as String,
            kind: SocialVaultSlotKind.fromWireName(
              (n['kind'] ?? s['kind']) as String,
            ),
            slotSecret: hex(s['slotSecretHex'] as String),
            wrapped: SocialVaultSealed.fromWire(
              nonce: s['nonce'] as String,
              ciphertext: s['wrappedKey'] as String,
            ),
          );
        }
        await expectLater(attempt, throwsA(isA<SocialVaultCryptoException>()));
      });
    }
  });

  group('derivation vectors', () {
    final d = vectors['derivation'] as Map<String, dynamic>;

    test('a bip39 vault derives the standard index-0 addresses', () async {
      final b = d['bip39'] as Map<String, dynamic>;
      final mnemonic = b['mnemonic'] as String;
      expect(
        MultiChainDerivation.solanaHdPath(0, SolanaDerivationScheme.standard),
        b['solanaPath'],
      );
      expect(
        await MultiChainDerivation.getSolanaAddressForScheme(
          mnemonic,
          0,
          SolanaDerivationScheme.standard,
        ),
        b['solana'],
      );
      expect(MultiChainDerivation.ethereumHdPath(0), b['ethereumPath']);
      expect(
        await MultiChainDerivation.getEthereumAddressAtIndex(mnemonic, 0),
        b['ethereum'],
      );
      expect(
        await MultiChainDerivation.getTezosAddressAtIndex(mnemonic, 0),
        b['tezos'],
      );
    });
  });

  group('round trip and validation', () {
    test('random vault: seal, wrap, unwrap, open', () async {
      final vaultId = SocialVaultCrypto.newVaultId();
      final slotId = SocialVaultCrypto.newSlotId();
      final dataKey = SocialVaultCrypto.newDataKey();
      final secret = SocialVaultCrypto.randomBytes(32);
      // Sealing refuses anything that is not a valid phrase.
      const payload = SocialVaultPayload(
        'abandon abandon abandon abandon abandon abandon abandon abandon '
        'abandon abandon abandon about',
      );

      final sealed = await SocialVaultCrypto.sealPayload(
        vaultId: vaultId,
        dataKey: dataKey,
        payload: payload,
      );
      final wrapped = await SocialVaultCrypto.wrapDataKey(
        vaultId: vaultId,
        slotId: slotId,
        kind: SocialVaultSlotKind.platform,
        slotSecret: secret,
        dataKey: dataKey,
      );
      final unwrapped = await SocialVaultCrypto.unwrapDataKey(
        vaultId: vaultId,
        slotId: slotId,
        kind: SocialVaultSlotKind.platform,
        slotSecret: secret,
        wrapped: wrapped,
      );
      final opened = await SocialVaultCrypto.openPayload(
        vaultId: vaultId,
        dataKey: unwrapped,
        sealed: sealed,
      );
      expect(opened.mnemonic, payload.mnemonic);
    });

    test('two seals of one payload never share a nonce', () async {
      final vaultId = SocialVaultCrypto.newVaultId();
      final dataKey = SocialVaultCrypto.newDataKey();
      // Sealing refuses anything that is not a valid phrase.
      const payload = SocialVaultPayload(
        'abandon abandon abandon abandon abandon abandon abandon abandon '
        'abandon abandon abandon about',
      );
      final a = await SocialVaultCrypto.sealPayload(
        vaultId: vaultId,
        dataKey: dataKey,
        payload: payload,
      );
      final b = await SocialVaultCrypto.sealPayload(
        vaultId: vaultId,
        dataKey: dataKey,
        payload: payload,
      );
      expect(a.nonceWire, isNot(b.nonceWire));
    });

    test('a wrong slot secret does not unwrap', () async {
      final s = slots.first;
      final secret = hex(s['slotSecretHex'] as String)..[0] ^= 1;
      await expectLater(
        SocialVaultCrypto.unwrapDataKey(
          vaultId: s['vaultId'] as String,
          slotId: s['slotId'] as String,
          kind: SocialVaultSlotKind.fromWireName(s['kind'] as String),
          slotSecret: secret,
          wrapped: SocialVaultSealed.fromWire(
            nonce: s['nonce'] as String,
            ciphertext: s['wrappedKey'] as String,
          ),
        ),
        throwsA(isA<SocialVaultCryptoException>()),
      );
    });

    test('rejects malformed lengths and encodings', () async {
      expect(
        () => SocialVaultCrypto.sealPayload(
          vaultId: SocialVaultCrypto.newVaultId(),
          dataKey: Uint8List(31),
          payload: const SocialVaultPayload('x'),
        ),
        throwsA(isA<SocialVaultCryptoException>()),
      );
      expect(
        () => SocialVaultCrypto.decodeBase64UrlNoPad('AAAA='),
        throwsA(isA<SocialVaultCryptoException>()),
      );
      expect(
        () => SocialVaultCrypto.sealPayload(
          vaultId: 'c2hvcnQ',
          dataKey: Uint8List(32),
          payload: const SocialVaultPayload('x'),
        ),
        throwsA(isA<SocialVaultCryptoException>()),
      );
    });

    test('refuses unknown payload versions and kinds', () {
      for (final json in [
        '{"v":2,"kind":"bip39","mnemonic":"a"}',
        '{"v":1,"kind":"raw","mnemonic":"a"}',
        '{"v":1,"mnemonic":"a"}',
        '{"v":1,"kind":"bip39"}',
        '[]',
        'not json',
      ]) {
        expect(
          () => SocialVaultPayload.fromJsonString(json),
          throwsA(isA<SocialVaultCryptoException>()),
          reason: json,
        );
      }
    });

    test('refuses the removed raw-key kind by name, quoting no key', () {
      // `web3auth-legacy` was in the format before it shipped. A payload of
      // that kind (well formed, real key lengths) must be refused with an
      // error that names the kind, never read as a wallet and never echoed.
      final secret = '0f' * 32;
      final json =
          '{"v":1,"kind":"web3auth-legacy","ed25519":"${'ab' * 64}",'
          '"secp256k1":"$secret"}';
      expect(
        () => SocialVaultPayload.fromJsonString(json),
        throwsA(
          isA<SocialVaultCryptoException>()
              .having(
                (e) => e.message,
                'message',
                allOf(
                  contains('unknown payload kind'),
                  contains('web3auth-legacy'),
                ),
              )
              .having((e) => e.toString(), 'text', isNot(contains(secret))),
        ),
      );
    });

    test('a sealed payload of an unknown kind does not open', () async {
      // The same refusal through the path a vault actually takes: valid
      // ciphertext under the right key and vault id, wrong kind inside.
      final vaultId = SocialVaultCrypto.newVaultId();
      final dataKey = SocialVaultCrypto.newDataKey();
      final nonce = SocialVaultCrypto.randomBytes(12);
      final box = await AesGcm.with256bits().encrypt(
        utf8.encode('{"v":1,"kind":"web3auth-legacy","ed25519":"00"}'),
        secretKey: SecretKey(dataKey),
        nonce: nonce,
        aad: utf8.encode(SocialVaultCrypto.payloadAad(vaultId)),
      );
      await expectLater(
        SocialVaultCrypto.openPayload(
          vaultId: vaultId,
          dataKey: dataKey,
          sealed: SocialVaultSealed(
            nonce: Uint8List.fromList(nonce),
            ciphertext: Uint8List.fromList([
              ...box.cipherText,
              ...box.mac.bytes,
            ]),
          ),
        ),
        throwsA(
          isA<SocialVaultCryptoException>().having(
            (e) => e.message,
            'message',
            contains('unknown payload kind'),
          ),
        ),
      );
    });

    test('payload toString never prints the secret', () {
      const payload = SocialVaultPayload('alpha beta gamma');
      expect(payload.toString(), isNot(contains('alpha')));
    });

    test('the vault key verifies its own request signature', () async {
      final vaultId = SocialVaultCrypto.newVaultId();
      final keyPair = await SocialVaultCrypto.vaultKeyPair(
        dataKey: SocialVaultCrypto.newDataKey(),
        vaultId: vaultId,
      );
      final body = utf8.encode('{}');
      final signature = await SocialVaultCrypto.signRequest(
        keyPair: keyPair,
        method: 'post',
        path: '/v2/social-vault/rewrap',
        vaultId: vaultId,
        revision: 1,
        body: body,
        timestamp: 1,
      );
      final message = SocialVaultCrypto.requestMessage(
        method: 'POST',
        path: '/v2/social-vault/rewrap',
        vaultId: vaultId,
        revision: 1,
        body: body,
        timestamp: 1,
      );
      final ok = await Ed25519().verify(
        utf8.encode(message),
        signature: Signature(
          SocialVaultCrypto.decodeBase64UrlNoPad(signature),
          publicKey: await keyPair.extractPublicKey(),
        ),
      );
      expect(ok, isTrue);
    });
  });
}
